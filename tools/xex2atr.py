def atr_header(image_size: int) -> bytes:
    """16-byte ATR header: 128-byte sectors, data size in 16-byte paragraphs.

    The paragraph count excludes the 16-byte ATR header (standard DOS 2.5 /
    GAMES002 images do the same).  Some loaders tolerate the +1 off-by-one,
    but keep it correct for other ATR users.
    """
    data_size = image_size - 16
    if data_size % 16:
        raise ValueError("ATR data size must be a multiple of 16")
    paras = data_size // 16
    h = bytearray(16)
    h[0:2] = b"\x96\x02"
    h[2:4] = struct.pack("<H", paras & 0xFFFF)
    h[4:6] = struct.pack("<H", SECTOR)          # 128
    h[6:8] = struct.pack("<H", (paras >> 16) & 0xFFFF)
    return bytes(h)


BASIC_INIT = 0x0400
BASIC_INIT_CODE = bytes([0xA9, 0xFD, 0x8D, 0x01, 0xD3, 0x60])  # LDA #$FD / STA $D301 / RTS


def xex_segments(xex: bytes):
    """Yield (start, end) of each binary-load segment, skipping $FFFF markers."""
    i = 0
    while i + 1 < len(xex):
        if xex[i] == 0xFF and xex[i + 1] == 0xFF:
            i += 2
            continue
        if i + 4 > len(xex):
            return
        start, end = struct.unpack_from("<HH", xex, i)
        i += 4
        if end < start or i + (end - start + 1) > len(xex):
            return
        yield start, end
        i += end - start + 1


def patch_basic_init(xex: bytes) -> bytes:
    """Prepend a tiny INITAD segment that clears PORTB bit 1 before high segments.

    The standard binary loader (Atari OS, MiSTer, Tang, our 6502 loader) calls
    INITAD after loading a segment that contains $02E2.  With this segment first,
    BASIC is already off when a later segment writes $A000-$BFFF (River Raid).
    This also makes the XEX work in emulators that start with BASIC on.
    """
    if xex[:2] != b"\xFF\xFF":
        return xex
    segs = list(xex_segments(xex))
    if not segs:
        return xex
    # Do not stomp a game that already uses $0400 or has its own INITAD.
    for start, end in segs:
        if start <= BASIC_INIT + len(BASIC_INIT_CODE) - 1 and end >= BASIC_INIT:
            return xex
        if start <= 0x02E2 <= end:
            return xex

    init = (b"\xFF\xFF" + struct.pack("<HH", BASIC_INIT, BASIC_INIT + len(BASIC_INIT_CODE) - 1)
            + BASIC_INIT_CODE)
    vec = (b"\xFF\xFF" + struct.pack("<HH", 0x02E2, 0x02E3)
           + struct.pack("<H", BASIC_INIT))
    out = b"\xFF\xFF" + init + vec + xex[2:]
    # The loader presets RUNAD to the first segment ($0400); if the original
    # file had no RUNAD, add one pointing at its original first segment.
    if not any(s <= 0x02E0 <= e for s, e in segs):
        out += (b"\xFF\xFF" + struct.pack("<HH", 0x02E0, 0x02E1)
                + struct.pack("<H", segs[0][0]))
    return out


def build(xex: bytes) -> tuple[bytes, int]:
    if len(xex) < 2 or xex[0] != 0xFF or xex[1] != 0xFF:
        raise ValueError("not a XEX: missing FF FF header")

    xex = patch_basic_init(xex)
    data_sectors = (len(xex) + SECTOR - 1) // SECTOR
    nsectors = (LOADER_FIRSTSEC - 1) + data_sectors
    image = bytearray(16 + nsectors * SECTOR)

    def put(sector: int, data: bytes | bytearray) -> None:
        off = 16 + (sector - 1) * SECTOR
        n = min(len(data), SECTOR)
        image[off:off + n] = data[:n]

    loader = bytearray(LOADER)
    size = len(xex)
    loader[REM_OFFSETS[0]] = size & 0xFF
    loader[REM_OFFSETS[1]] = (size >> 8) & 0xFF
    loader[REM_OFFSETS[2]] = (size >> 16) & 0xFF
    for i in range(LOADER_BLDCNT):
        put(i + 1, loader[i * SECTOR:(i + 1) * SECTOR])

    for i in range(data_sectors):
        put(LOADER_FIRSTSEC + i, xex[i * SECTOR:(i + 1) * SECTOR])

    image[0:16] = atr_header(len(image))
    return bytes(image), data_sectors


def main() -> int:
    ap = argparse.ArgumentParser(description="Convert Atari XEX to a bootable 128-byte ATR")
    ap.add_argument("input", type=Path)
    ap.add_argument("output", nargs="?", type=Path)
    args = ap.parse_args()

    xex = args.input.read_bytes()
    out = args.output or args.input.with_suffix(".atr")
    image, data_sectors = build(xex)
    out.write_bytes(image)
    print(f"XEX {len(xex)} bytes -> {data_sectors} data sectors -> ATR {len(image)} bytes")
    print(f"boot: sectors 1-{LOADER_BLDCNT} loader (BASIC off), data@ {LOADER_FIRSTSEC}..{LOADER_FIRSTSEC + data_sectors - 1}")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as e:
        print(f"xex2atr: {e}", file=sys.stderr)
        raise SystemExit(1)
