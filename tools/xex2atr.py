#!/usr/bin/env python3
"""
XEX -> bootable ATR (host-side loader, no firmware/RTL changes).

The Atari side is the "v2" 6502 XEX boot loader from the Tang Nano 20K
project (firmware/xex_loader.py).  It is served as a normal 128-byte-sector
D1: disk:

    sectors 1..4  : 6502 loader (512 bytes)
    sector  5..   : raw .xex bytes, 128 per sector

The loader uses the OS SIO vector (SIOV) to pull the raw XEX bytes, processes
the binary-load format (segments, $FFFF separators, INITAD/RUNAD), and writes
each segment directly to its destination address.  Unlike the older 179-byte
MiST loader, it keeps no state in zero page and no buffer in page 6, so games
that use $80-$FF or $0600 are not corrupted.

BASIC OFF
---------
The loader starts with

    LDA #$FD
    STA $D301

so PORTB bit 1 (BASIC ROM) is cleared before any segment is loaded.  This is
the same state the XL OS sets when OPTION is held at cold boot.  We cannot rely
on a held key here: on Karabas the OSD/boot path may not pass OPTION through,
and holding OPTION with no bootable disk enters the self-test.  The write keeps
OS ROM enabled.  This loader targets XL/XE; the Atari 800 memory map has no
BASIC bank at $D301.

Why this loader
---------------
MiSTer's "Load XEX" menu uses an HPS/DMA + PBI path that is not available on
Karabas.  MiSTer's virtual-D1 path and the Tang core both need BASIC disabled
for high-memory XEX files (e.g. River Raid has a segment at $9FF0-$BFFF, which
overlaps the BASIC ROM at $A000-$BFFF).  MiSTer/Tang do it by holding OPTION
during cold boot; this loader does it explicitly.

Usage:
    tools/xex2atr.py GAME.XEX [GAME.ATR]

Notes:
  * XEX must start with FF FF.
  * The ATR is single density (128-byte sectors); the existing
    atari_atr_loader + atari_sio_disk serve it unchanged.
"""

