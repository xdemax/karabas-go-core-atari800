`timescale 1ns / 1ps
`default_nettype none
/*-------------------------------------------------------------------------------------------------------------------
--
-- tb_atari_machine.v - full Atari 800XL machine (atari800_machine) on a behavioral SRAM.
--
--   * 28.571 MHz PAL clock, 320K RAMBO/Compy, internal Altirra OS/BASIC;
--   * the ATR image is preloaded at 0x300000, atari_sio_disk serves it;
--   * video: atari_video 720x576 output (hs/vs/de), a PPM can be captured;
--   * audio: audio_l is logged at 55.8 kHz (every 512 clocks).
--
-- The image is a .hex file, one byte per line ($readmemh), generated by
-- sim/gen_atr_hex.py.  The geometry parameters below match Numen Side A
-- (133136 bytes, 128-byte sectors, 1040 sectors); regenerate them for another
-- image.
--
-------------------------------------------------------------------------------------------------------------------*/
module tb_atari_machine;

localparam ATR_SIZE   = 133136;
localparam ATR_SSIZE  = 128;
localparam ATR_SCOUNT = 1040;
localparam RAM_SEL    = 3'd2;        // 2: 320K Compy, 3: 320K Rambo
parameter  MAX_CYCLES = 2000000;     // 70 ms; raise for the demo intro

reg clk = 1'b0;
always #17.5 clk = ~clk;             // 28.571 MHz

reg reset = 1'b1, power_reset = 1'b1, reset_host = 1'b1;
initial begin
	#2000;
	reset = 1'b0;
	power_reset = 1'b0;
	reset_host = 1'b0;
end

// ---------------------------------------------------------------- SRAM model (4 MB bytes)
wire [20:0] MA;
wire [15:0] MD;
wire [1:0]  MWR_N, MRD_N;
reg  [7:0]  mem [0:4194303];
reg  [7:0]  atr [0:ATR_SIZE-1];
integer i;

assign MD = (MRD_N != 2'b11) ? { mem[{MA, 1'b1}], mem[{MA, 1'b0}] } : 16'hzzzz;

// Active-low byte write enables: low byte = MWR_N[0]==0, high byte = MWR_N[1]==0.
// Write on the falling edge: the controller changes MA/MWR_N/MD on the rising edge,
// so the values are stable here.  (A combinational always @(*) over mem creates a
// delta-cycle loop through the MD read and hangs ISim at time 0.)
always @(negedge clk) begin
	if (MWR_N[0] == 1'b0) mem[{MA, 1'b0}] = MD[7:0];
	if (MWR_N[1] == 1'b0) mem[{MA, 1'b1}] = MD[15:8];
end

initial begin
	$readmemh("numen_a.hex", atr);
	// 320K Atari RAM is enough for this demo; the rest of the 4 MB stays X and
	// is never read (cart_sel=0).  Zeroing all 4M took ~1 minute in ISim.
	for (i = 0; i < 25'h50000; i = i + 1)
		mem[i] = 8'h00;
	for (i = 0; i < ATR_SIZE; i = i + 1)
		mem[25'h300000 + i] = atr[i];
	$display("tb_atari_machine: ATR %0d bytes loaded at 0x300000, ssize %0d, scount %0d",
	         ATR_SIZE, ATR_SSIZE, ATR_SCOUNT);
end

// ---------------------------------------------------------------- machine
wire [23:0] rgb;
wire        hs, vs, de;
wire signed [17:0] audio_l, audio_r;
wire        sio_command, sio_txd, sio_clock, sio_motor, sio_rxd;
wire        dsk_req;
wire [24:0] dsk_addr;
wire [7:0]  dsk_data;
wire        dsk_ack;
wire [7:0]  dbg_defer;

atari800_machine #(.HS_START(10'd840), .HS_END(10'd912)) dut (
	.clk            (clk),
	.clk_vid        (clk),
	.reset          (reset),
	.power_reset    (power_reset),
	.force_cold     (1'b0),
	.reset_host     (reset_host),
	.pause          (1'b0),

	.kb_scancode    (8'd0),
	.kb_scancode_upd(1'b0),
	.joy_l          (13'd0),
	.joy_r          (13'd0),
	.sw_joy_swap    (1'b0),

	.ram_sel        (RAM_SEL),
	.cart_sel       (8'd0),
	.pal            (1'b1),
	.clip_sides     (1'b0),
	.gtia_xcolor    (1'b0),

	.ld_req         (1'b0),
	.ld_addr        (25'd0),
	.ld_data        (8'd0),

	.rgb            (rgb),
	.hs             (hs),
	.vs             (vs),
	.de             (de),

	.audio_l        (audio_l),
	.audio_r        (audio_r),

	.sio_command    (sio_command),
	.sio_rxd        (sio_rxd),
	.sio_txd        (sio_txd),
	.sio_clock      (sio_clock),
	.sio_motor      (sio_motor),

	.dsk_req        (dsk_req),
	.dsk_addr       (dsk_addr),
	.dsk_data       (dsk_data),
	.dsk_ack        (dsk_ack),
	.dbg_defer      (dbg_defer),

	.MA             (MA),
	.MD             (MD),
	.MWR_N          (MWR_N),
	.MRD_N          (MRD_N)
);

// ---------------------------------------------------------------- SIO disk
wire [7:0] dbg_cmd_cnt, dbg_last_code, dbg_ack_cnt, dbg_tx_cnt, dbg_rx_byte;
wire [7:0] dbg_cmd_edges, dbg_bad_frames, dbg_flags;
wire [39:0] dbg_last_frame;

atari_sio_disk sio_disk (
	.clk            (clk),
	.reset          (reset),
	.atr_ssize      (16'd128),
	.atr_scount     (32'd1040),
	.atr_ready      (1'b1),
	.sio_command    (sio_command),
	.sio_txd        (sio_txd),
	.sio_clock      (sio_clock),
	.sio_rxd        (sio_rxd),
	.dsk_req        (dsk_req),
	.dsk_addr       (dsk_addr),
	.dsk_data       (dsk_data),
	.dsk_ack        (dsk_ack),
	.dbg_cmd_cnt    (dbg_cmd_cnt),
	.dbg_last_code  (dbg_last_code),
	.dbg_ack_cnt    (dbg_ack_cnt),
	.dbg_tx_cnt     (dbg_tx_cnt),
	.dbg_rx_byte    (dbg_rx_byte),
	.dbg_cmd_edges  (dbg_cmd_edges),
	.dbg_bad_frames (dbg_bad_frames),
	.dbg_flags      (dbg_flags),
	.dbg_last_frame (dbg_last_frame)
);

// ---------------------------------------------------------------- counters / logs
integer cycles = 0;
integer frames = 0;
integer hs_cnt = 0;
integer de_cnt = 0;
reg hs_d = 1'b0, vs_d = 1'b0;
integer afd;

initial afd = $fopen("audio.txt", "w");

always @(posedge clk) begin
	cycles <= cycles + 1;
	hs_d <= hs;
	vs_d <= vs;
	if (hs && !hs_d) hs_cnt <= hs_cnt + 1;
	if (vs && !vs_d) frames <= frames + 1;
	if (de) de_cnt <= de_cnt + 1;

	// audio at 55.8 kHz: one sample every 512 clocks
	if ((cycles & 9'h1FF) == 0)
		$fwrite(afd, "%0d\n", $signed(audio_l));

	if ((cycles % 1000000) == 0)
		$display("t=%0t cyc=%0d frames=%0d hs=%0d de=%0d | sio cmd=%0d ack=%0d tx=%0d bad=%0d last=%02x flags=%02x | defer=%0d",
		         $time, cycles, frames, hs_cnt, de_cnt,
		         dbg_cmd_cnt, dbg_ack_cnt, dbg_tx_cnt, dbg_bad_frames, dbg_last_code, dbg_flags, dbg_defer);

	if (cycles >= MAX_CYCLES) begin
		$display("tb_atari_machine: stop at %0d cycles, %0d frames, %0d hs, %0d de", cycles, frames, hs_cnt, de_cnt);
		$fclose(afd);
		$finish;
	end
end

endmodule
`default_nettype wire
